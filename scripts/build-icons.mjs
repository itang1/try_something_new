// Generates src/icons/paths.ts with the path data for only the Material Symbols the app uses,
// so the full 7,800-icon package never ships in the bundle. Run with `npm run icons`.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';

const UI_ICONS = [
  'accessible', 'ac_unit', 'account_balance', 'add', 'arrow_back', 'arrow_forward', 'beach_access', 'block', 'bolt', 'bookmark', 'calendar_month', 'check', 'check_circle',
  'chevron_right', 'close', 'content_cut', 'directions',
  'directions_car', 'directions_run', 'eco', 'explore', 'favorite', 'flight', 'family_restroom', 'grid_view', 'groups', 'house', 'help', 'info', 'hiking', 'history', 'flag', 'ios_share',
  'delete', 'keyboard_arrow_down', 'location_city', 'logout', 'location_on', 'my_location', 'notifications', 'open_in_new', 'park', 'payments', 'person', 'person_add', 'photo_camera', 'photo_library',
  'radio_button_unchecked', 'rainy', 'remove', 'restaurant', 'schedule', 'search', 'share', 'shopping_bag', 'shuffle', 'star', 'sunny', 'sync', 'trending_up', 'trophy', 'tune', 'undo',
];

const mapping = JSON.parse(readFileSync('design/icon-mapping.json', 'utf8'));
// A remote city can use only glyphs the installed app already has; others fall back to the activity's.
const cityGlyphs = readdirSync('data/cities').flatMap((f) =>
  JSON.parse(readFileSync(`data/cities/${f}`, 'utf8')).icons.flatMap((i) => (i.glyph ? [i.glyph] : [])),
);
const names = [...new Set([...Object.values(mapping).map((a) => a.material), ...cityGlyphs, ...UI_ICONS])].sort();

const dir = 'node_modules/@material-symbols/svg-400/rounded';
const paths = {};
for (const name of names) {
  const file = [`${dir}/${name}-fill.svg`, `${dir}/${name}.svg`].find(existsSync);
  if (!file) throw new Error(`No Material Symbol named "${name}"`);
  const svg = readFileSync(file, 'utf8');
  paths[name] = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
}

const lines = Object.entries(paths).map(([k, v]) => `  ${k}: '${v}',`);
writeFileSync(
  'src/icons/paths.ts',
  `// Generated by scripts/build-icons.mjs. Do not edit.\nexport const ICON_PATHS = {\n${lines.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`Wrote ${names.length} icons to src/icons/paths.ts`);
