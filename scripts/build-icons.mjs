// Generates src/icons/paths.ts with the path data for only the Material Symbols the app uses,
// so the full 7,800-icon package never ships in the bundle. Run with `npm run icons`.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const UI_ICONS = [
  'account_balance', 'beach_access', 'check_circle', 'content_cut', 'directions_car',
  'directions_run', 'eco', 'grid_view', 'help', 'hiking', 'history', 'location_city',
  'location_on', 'my_location', 'payments', 'radio_button_unchecked', 'restaurant',
  'schedule', 'search', 'shopping_bag', 'star', 'sunny', 'trophy',
];

const mapping = JSON.parse(readFileSync('design/icon-mapping.json', 'utf8'));
const names = [...new Set([...Object.values(mapping).map((a) => a.material), ...UI_ICONS])].sort();

const dir = 'node_modules/@material-symbols/svg-400/rounded';
const paths = {};
for (const name of names) {
  const file = [`${dir}/${name}-fill.svg`, `${dir}/${name}.svg`].find(existsSync);
  if (!file) throw new Error(`No Material Symbol named "${name}"`);
  const svg = readFileSync(file, 'utf8');
  paths[name] = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
}

const lines = Object.entries(paths).map(([k, v]) => `  ${k}: '${v}',`);
writeFileSync(
  'src/icons/paths.ts',
  `// Generated by scripts/build-icons.mjs. Do not edit.\nexport const ICON_PATHS = {\n${lines.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`Wrote ${names.length} icons to src/icons/paths.ts`);
